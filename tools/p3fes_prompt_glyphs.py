def bitmap(label, max_w, max_h):
    """Rows of '#'/'.' for label that fit inside max_w x max_h. label is a symbol name (ENTER, UP ...), one character, or short text:
    a symbol or single character uses the big 5x7 glyph; text uses big letters when they fit, else small 3x5 letters."""
    if label in G7:
        g = G7[label]
        if len(g[0]) <= max_w and len(g) <= max_h:
            return g
        label = label[:1]                       # too small for the symbol: its first letter
    text = [c for c in label.upper() if c in G7 and len(c) == 1][:3] or ["I"]
    if max_h >= 7 and 6 * len(text) - 1 <= max_w:
        rows = [""] * 7
        for i, c in enumerate(text):
            for y in range(7):
                rows[y] += G7[c][y].ljust(5, ".") + ("." if i < len(text) - 1 else "")
        return rows
    n = max(1, min(len(text), (max_w + 1) // 4))
    rows = [""] * 5
    for i, c in enumerate(text[:n]):
        for y in range(5):
            rows[y] += G5.get(c, G5["I"])[y] + ("." if i < n - 1 else "")
    return rows
