# SDL key names (the launcher's key settings) -> a symbol, or a short word shown in small letters
KEY_SYMBOL = {"Up": "UP", "Down": "DOWN", "Left": "LEFT", "Right": "RIGHT", "Return": "ENTER", "Backspace": "BACK",
              "Space": "SPACE", "Left Shift": "SHIFT", "Right Shift": "SHIFT", "Left Ctrl": "CTRL", "Tab": "TAB", "none": "NONE"}


def key_label(key):
    """What a keyboard key is called on its keycap: 'K' stays 'K', 'Return' becomes an Enter symbol, 'Keypad 5' is '5'."""
    k = str(key or "none")
    if k in KEY_SYMBOL:
        return KEY_SYMBOL[k]
    if k.startswith("Keypad "):
        k = k[7:]
    return k[:1].upper() if k else "NONE"


