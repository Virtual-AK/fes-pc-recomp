"""Log key for the PC window of PS2 Web Recomp: press TAB in the game window and a box with the last lines of dialogue
(speaker and text) appears over the bottom of the game; press TAB or Esc again to close it.

How it works: the dialogue log patch (ps2run_dialoglog_patch.py, PS2_DIALOG_LOG set, which the launcher always does) already notices every
new page of dialogue. This patch also keeps the last 40 pages in memory and, on TAB, opens a small borderless always-on-top window
(a second SDL window, so it works whichever way the game itself is drawn) placed over the bottom of the game window. The box has its own
small built-in font. While the box is open it has the keyboard focus, so the game stops getting key presses; close it to carry on.
Controller buttons still reach the game. Nothing about the game itself changes. Needs ps2run_dialoglog_patch.py applied first (it does not depend on any other window patch).

Run in the ps2-web-recomp folder:  python3 ps2run_logkey_patch.py [folder]
(patches runtime/include/ps2/system.hpp, runtime/src/system.cpp and host/window.cpp; idempotent; refuses unknown source)
Rebuild afterwards.
"""
