"""Builds the map file the HD texture patch reads (PS2_HDTEX).

  python3 p3fes_hdtex.py [--table hdtex-table-ntscu.tsv] [--mods hdmods] [--out hdtex.map]

The table only holds hashes and names of picture files (no game data). Each row ends in <packid>:<path inside the pack>;
this finds the pack folder under --mods (a folder whose name starts with the pack id), checks the picture exists, and
writes the row back with the absolute path. Rows whose picture is missing are left out and counted.
"""
import argparse
import collections
import os
import sys


def find_table(here=None):
    here = here or os.path.dirname(os.path.abspath(__file__))
    for c in (os.path.join(here, "hdtex-table-ntscu.tsv"), os.path.join(here, "hdtex", "hdtex-table-ntscu.tsv")):
        if os.path.isfile(c):
            return c
    return None


def build_map(table, mods, out=None, win_root=None):
    """Resolve the table against the pack folders under `mods`. Returns (rows_found, {packid: rows_missing}).
    With `out`, writes the map file the game reads; `win_root` is the Windows spelling of `mods` (one conversion, not one per picture)."""
    folders = []
    for d in sorted(os.listdir(mods)):
        p = os.path.join(mods, d)
        if os.path.isdir(p):
            folders.append((d, p))

    def packdirs(pid):
        return [p for d, p in folders if d == pid or d.startswith(pid)]

    found_rows = []
    missing = collections.Counter()
    cache = {}
    for line in open(table, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        f = line.rstrip("\r\n").split("\t")
        if len(f) < 10:
            continue
        pid, _, rel = f[9].partition(":")
        if pid not in cache:
            cache[pid] = packdirs(pid)
        hit = None
        for d in cache[pid]:
            c = os.path.join(d, *rel.split("/"))
            if os.path.isfile(c):
                hit = os.path.abspath(c)
                break
        if not hit:
            missing[pid] += 1
            continue
        if win_root:
            hit = win_root.replace("\\", "/").rstrip("/") + "/" + os.path.relpath(hit, os.path.abspath(mods)).replace(os.sep, "/")
        f[9] = hit
        found_rows.append("\t".join(f))
    if out:
        with open(out, "w", newline="\n", encoding="utf-8") as fh:
            fh.write("# generated by p3fes_hdtex.py; hashes -> HD pictures\n")
            fh.write("\n".join(found_rows) + "\n")
    return len(found_rows), dict(missing)


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--table", default=None)
    ap.add_argument("--mods", default=os.path.join(here, "hdmods"))
    ap.add_argument("--out", default=os.path.join(here, "hdtex.map"))
    a = ap.parse_args(argv)
    table = a.table or find_table(here)
    if not table or not os.path.isfile(table):
        print("table not found (pass --table)")
        return 2
    if not os.path.isdir(a.mods):
        print("mods folder not found: %s" % a.mods)
        return 2
    rows, missing = build_map(table, a.mods, a.out)
    print("wrote %s: %d textures" % (a.out, rows))
    for k, v in sorted(missing.items()):
        print("  %d rows skipped, picture missing in pack '%s'" % (v, k))
    return 0 if rows else 1


if __name__ == "__main__":
    sys.exit(main())
